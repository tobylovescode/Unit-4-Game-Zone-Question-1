public class Card
{
    private char suit;
    private int value;

    public char getSuit()
    {
        return suit;
    }
    public void setSuit(char suit)
    {
        this.suit = suit;
    }
    public int getValue()
    {
        return value;
    }
    public void setValue(int value)
    {
        this.value = value;
    }
}